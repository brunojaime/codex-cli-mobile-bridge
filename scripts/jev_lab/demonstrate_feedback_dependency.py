#!/usr/bin/env python3
"""Replay an observed Bridge defect through the quality runner, in isolation.

The baseline is captured source, not an injected fault. Fixtures and repositories
are disposable. The correction is supplied by the developer, not generated by Jev.
At most one real Jev call is made, with only isolated regression output.
"""

from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path
import shutil
import subprocess
import sys
import tempfile

sys.path.insert(0, str(Path(__file__).resolve().parents[2]))

from backend.app.application.services.jev_advisor import JevAdvisor
from backend.app.application.services.pipeline_quality_service import (
    PipelineQualityService,
    QualityError,
)
from backend.app.infrastructure.config.settings import Settings

ROOT = Path(__file__).resolve().parents[2]


def digest(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--before-source", type=Path, required=True)
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--live-jev", action="store_true")
    args = parser.parse_args()
    settings = Settings()
    if args.live_jev and not settings.open_router_api_key:
        raise SystemExit("Configure OPEN_ROUTER_API_KEY using Secrets")
    advisor = JevAdvisor(
        enabled=args.live_jev,
        api_key=settings.open_router_api_key.get_secret_value()
        if settings.open_router_api_key
        else None,
        model=settings.pipeline_quality_jev_model,
        timeout=5,
    )
    relative_service = Path(
        "backend/app/application/services/pipeline_quality_service.py"
    )
    source_hashes = {
        "before": digest(args.before_source),
        "after": digest(ROOT / relative_service),
        "unchanged_regression": digest(
            ROOT / "tests/test_pipeline_feedback_dependencies.py"
        ),
    }
    with tempfile.TemporaryDirectory(
        prefix="bridge-feedback-demonstration-"
    ) as directory:
        base = Path(directory)
        checkout = base / "checkout"
        checkout.mkdir()
        for relative in (
            relative_service,
            Path("backend/app/application/services/jev_advisor.py"),
            Path("backend/app/domain/entities/pipeline_quality.py"),
        ):
            target = checkout / relative
            target.parent.mkdir(parents=True, exist_ok=True)
            shutil.copyfile(
                args.before_source if relative == relative_service else ROOT / relative,
                target,
            )
            for parent in target.parents:
                if parent == checkout:
                    break
                (parent / "__init__.py").touch()
        shutil.copyfile(
            ROOT / "tests/test_pipeline_feedback_dependencies.py",
            checkout / "scenario.py",
        )
        (checkout / ".gitignore").write_text("__pycache__/\n")
        for argv in (
            ["init", "-q"],
            ["add", "."],
            [
                "-c",
                "user.name=Demo",
                "-c",
                "user.email=demo@example.invalid",
                "commit",
                "-qm",
                "Captured Bridge source before feedback dependency fix",
            ],
        ):
            subprocess.run(
                ["git", "-C", str(checkout), *argv], check=True, capture_output=True
            )
        service = PipelineQualityService(
            database_path=base / "ledger.sqlite", allowed_roots=[base], advisor=advisor
        )
        packet = service.register(
            workspace=str(checkout),
            work_item_id="feedback-must-respect-required-dependencies",
            links={"stage_id": "isolated-demonstration"},
            contract={
                "project_id": "codex-cli-mobile-bridge",
                "environment": "local",
                "component_ids": ["pipeline-quality", "developer-feedback"],
                "criteria": [
                    {
                        "id": "feedback-dependencies",
                        "description": "Feedback cannot be verified while a required dependency lacks current evidence, and recovers after rechecking the dependency",
                        "check_ids": ["regression"],
                    }
                ],
                "checks": [
                    {
                        "id": "regression",
                        "argv": [sys.executable, "-B", "scenario.py"],
                        "timeout_seconds": 45,
                    }
                ],
            },
        )
        before = service.execute(packet["id"], attempt_key="captured-before")
        assert not before["quality"]["verified"]
        gate_before = service.stage_gate(str(checkout), "isolated-demonstration")
        try:
            service.close(packet["id"])
        except QualityError:
            close_blocked = True
        else:
            close_blocked = False
        assert close_blocked and not gate_before["verified"]

        shutil.copyfile(ROOT / relative_service, checkout / relative_service)
        assert digest(checkout / "scenario.py") == source_hashes["unchanged_regression"]
        after = service.execute(packet["id"], attempt_key="corrected-source")
        assert after["quality"]["verified"]
        gate_after = service.stage_gate(str(checkout), "isolated-demonstration")
        lesson = service.save_lesson(
            packet_id=packet["id"],
            failed_receipt_id=before["receipt_ids"][0],
            passed_receipt_id=after["receipt_ids"][0],
            symptom="Feedback reports verified while its work item is blocked by an unverified required dependency",
            cause_hypothesis="Feedback aggregation copied criterion states but omitted packet dependency blockers",
            resolution="Propagate dependency blockers into each mapped feedback item; verified criteria become blocked until prerequisite evidence is current",
            conditions="Bridge feedback aggregation with declared packet dependencies; own criteria passing and prerequisite changed, missing or unverified",
        )
        # Deliberate final perturbation, distinct from the naturally observed defect.
        with (checkout / relative_service).open("a") as handle:
            handle.write(
                "\n# Demonstration: a later source change requires new evidence.\n"
            )
        stale = service.status(packet["id"])
        assert not stale["verified"]
        rechecked = service.execute(packet["id"], attempt_key="recheck-later-change")
        assert rechecked["quality"]["verified"]
        service.close(packet["id"])

        receipts = service._list("receipt", packet["id"])
        observations = [
            json.JSONDecoder().raw_decode(r["output_excerpt"])[0] for r in receipts
        ]
        advice = before["diagnosis"]["advice"]
        result = {
            "scope": "Actual defect in locally implemented Bridge feedback aggregation; isolated fixtures; no deployment or customer data",
            "repair_author": "Developer inspected and corrected code; Jev did not generate the patch",
            "source_hashes": source_hashes,
            "criteria": before["quality"]["contract"]["criteria"],
            "before_fix": observations[0],
            "after_fix": observations[1],
            "checks": {
                "real_regression_failed_before": receipts[0]["status"] == "failed",
                "technical_close_blocked_before": close_blocked,
                "stage_gate_blocked_before": not gate_before["verified"],
                "same_test_passed_after": receipts[1]["status"] == "passed",
                "stage_gate_passed_after": gate_after["verified"],
                "lesson_has_failure_and_pass": lesson["status"] == "verified_repair",
                "later_source_change_invalidated_evidence": not stale["verified"],
                "later_change_rechecked": rechecked["quality"]["verified"],
            },
            "receipts": [
                {
                    key: receipt.get(key)
                    for key in (
                        "id",
                        "status",
                        "exit_code",
                        "source",
                        "source_after",
                        "command_digest",
                        "created_at",
                        "finished_at",
                        "duration_ms",
                        "output_excerpt",
                        "output_digest",
                    )
                }
                for receipt in receipts
            ],
            "jev": advice,
            "reported_cost_usd": advice.get("cost"),
            "lesson": lesson,
            "productivity_conclusion": "Not measured: one developer-led repair, no randomized or timed A/B/C comparison",
            "remote_mutations": 0,
        }
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(json.dumps(result, ensure_ascii=False, indent=2) + "\n")
    print(
        json.dumps(
            {
                "output": str(args.output),
                "checks_passed": sum(result["checks"].values()),
                "jev_status": advice["status"],
                "cost_usd": result["reported_cost_usd"],
            }
        )
    )


if __name__ == "__main__":
    main()
